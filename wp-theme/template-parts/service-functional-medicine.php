        <h2>What Is Functional Medicine?</h2>
        <p>Functional medicine is a systems-biology approach to healthcare that identifies and addresses the underlying root causes of disease. Rather than suppressing symptoms with medication alone, Dr. Akoury investigates the intricate web of factors — genetic, environmental, lifestyle, and physiological — that contribute to chronic illness.</p>
        <p>Unlike conventional medicine, which typically specialises in organ systems (cardiology, gastroenterology, endocrinology), functional medicine sees the body as an integrated whole. A problem in one system almost always reflects imbalances elsewhere. By viewing the entire patient, we can craft treatments that heal at the source.</p>

